// String datatype
let name = "Harshad";

// Number datatype
let age = 21;

// Boolean datatype
let isStudent = true;

// Undefined datatype
let value;

// Null datatype
let emptyValue = null;

// Arrow Function
const displayData = () => {
    console.log("Name:", name);
    console.log("Age:", age);
    console.log("Is Student:", isStudent);
    console.log("Value:", value);
    console.log("Empty Value:", emptyValue);
};

// Function Call
displayData();